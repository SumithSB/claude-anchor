//! Routes file (`~/.claude-anchor/routes`) and folder → account resolution. Port of Store.swift
//! `routesText` and shell/anchor.zsh `_anchor_resolve`. Also Claude Code's project folder naming.

use crate::fsx;
use crate::model::{Config, Limits};
use crate::paths::Paths;
use std::collections::HashMap;

const TAB_MSG: &str = "That folder name has a tab or line break in it, so it can't be used for a rule.";
const ABS_MSG: &str = "Choose a full folder path for the rule.";

/// Routes text: rules longest path first, then `default\t<dir or ->`. A rule with allowOverflow whose
/// account is at/over the threshold routes to the default account instead.
pub fn routes_text(cfg: &Config, limits: &HashMap<String, Limits>, paths: &Paths) -> String {
    let dir = |id: &str| match cfg.account(id) {
        Some(a) if !paths.is_primary(&a.dir) => a.dir.clone(),
        _ => "-".to_string(),
    };
    let hot = |id: &str| limits.get(id).is_some_and(|l| l.peak() >= cfg.overflow_threshold);
    let mut rules: Vec<_> = cfg.rules.iter().collect();
    rules.sort_by_key(|r| std::cmp::Reverse(r.path.chars().count()));
    let mut out = String::from("# generated by Claude Anchor — edit in the app\n");
    for r in rules.into_iter().filter(|r| !r.path.contains(['\t', '\n', '\r'])) {
        let id = if r.allow_overflow && hot(&r.account_id) { &cfg.default_id } else { &r.account_id };
        out.push_str(&format!("{}\t{}\n", r.path, dir(id)));
    }
    out.push_str(&format!("default\t{}\n", dir(&cfg.default_id)));
    out
}

/// Writes routes_text to paths.routes() (private dir, 0600, atomic).
pub fn write_routes(cfg: &Config, limits: &HashMap<String, Limits>, paths: &Paths) -> std::io::Result<()> {
    fsx::ensure_dir(&paths.anchor)?;
    fsx::write_secure(&paths.routes(), routes_text(cfg, limits, paths).as_bytes(), 0o600)
}

/// Config dir for `dir` from routes text: None = primary ("-"), Some(config dir) otherwise.
pub fn resolve(routes: &str, dir: &str) -> Option<String> { resolve_in(routes, dir, cfg!(windows)) }

/// Drops Windows' verbatim prefix (`\\?\C:\x` → `C:\x`, `\\?\UNC\srv\share` → `\\srv\share`), as canonicalize returns.
fn plain(p: &str) -> String {
    if let Some(r) = p.strip_prefix(r"\\?\UNC\") { format!(r"\\{r}") }
    else { p.strip_prefix(r"\\?\").unwrap_or(p).to_string() }
}

/// Comparable form of a folder: on Windows lowercase with `\`; no trailing separator except at a root.
fn key(p: &str, windows: bool) -> String {
    let mut s = if windows { plain(&p.replace('/', "\\")).to_lowercase() } else { p.to_string() };
    let sep = if windows { '\\' } else { '/' };
    while s.len() > 1 && s.ends_with(sep) && !(windows && s.len() == 3 && s.as_bytes()[1] == b':') {
        s.pop();
    }
    s
}

fn resolve_in(routes: &str, dir: &str, windows: bool) -> Option<String> {
    let sep = if windows { '\\' } else { '/' };
    let dir = key(dir, windows);
    let mut def = "-";
    let mut best: Option<(usize, &str)> = None; // (rule path length, config dir)
    for line in routes.lines() {
        if line.is_empty() || line.starts_with('#') { continue; }
        let Some((p, cfg)) = line.split_once('\t') else { continue };
        if p == "default" { def = cfg; continue; }
        if p.is_empty() { continue; }
        let p = key(p, windows);
        // A root (ends in a separator) covers everything under it, e.g. "/" or "C:\".
        let hit = if p.ends_with(sep) {
            dir.starts_with(&p)
        } else {
            dir == p || dir.strip_prefix(&p).is_some_and(|r| r.starts_with(sep))
        };
        if hit && best.is_none_or(|(n, _)| p.len() > n) { best = Some((p.len(), cfg)); }
    }
    let cfg = best.map_or(def, |(_, c)| c);
    (cfg != "-").then(|| cfg.to_string())
}

/// Claude Code's folder name under `<config>/projects/` for a cwd.
pub fn project_slug(cwd: &str) -> String {
    let units: Vec<u16> = cwd.encode_utf16().collect();
    let slug: String = units
        .iter()
        .map(|&u| if u < 128 && (u as u8).is_ascii_alphanumeric() { u as u8 as char } else { '-' })
        .collect();
    if slug.len() <= 200 { return slug; }
    // Java-style int32 hash over the original UTF-16 units, as Claude Code computes it.
    let h = units.iter().fold(0i32, |h, &u| h.wrapping_shl(5).wrapping_sub(h).wrapping_add(u as i32));
    format!("{}-{}", &slug[..200], base36(i64::from(h).unsigned_abs()))
}

fn base36(mut n: u64) -> String {
    const DIGITS: &[u8] = b"0123456789abcdefghijklmnopqrstuvwxyz";
    let mut out = Vec::new();
    loop {
        out.push(DIGITS[(n % 36) as usize] as char);
        n /= 36;
        if n == 0 { break; }
    }
    out.iter().rev().collect()
}

/// Normalises a folder for a rule; Err is a user-facing message.
pub fn normalize_rule_path(path: &str) -> Result<String, String> { normalize_in(path, cfg!(windows)) }

fn normalize_in(path: &str, windows: bool) -> Result<String, String> {
    if path.contains(['\t', '\n', '\r']) { return Err(TAB_MSG.into()); }
    let s = if windows { plain(&path.replace('/', "\\")) } else { path.to_string() };
    let sep = if windows { '\\' } else { '/' };
    // Split off the root: "/", "C:\" or "\\server\share". Anything else is not absolute.
    let (root, rest): (&str, &str) = if !windows {
        let Some(rest) = s.strip_prefix('/') else { return Err(ABS_MSG.into()) };
        ("/", rest)
    } else if s.len() >= 3 && s.as_bytes()[0].is_ascii_alphabetic() && s.as_bytes()[1] == b':' && s.as_bytes()[2] == b'\\' {
        (&s[..3], &s[3..])
    } else if let Some(body) = s.strip_prefix("\\\\") {
        let mut parts = body.splitn(3, '\\');
        match (parts.next(), parts.next()) {
            (Some(server), Some(share)) if !server.is_empty() && !share.is_empty() => {
                let end = 2 + server.len() + 1 + share.len();
                (&s[..end], &s[end..])
            }
            _ => return Err(ABS_MSG.into()),
        }
    } else {
        return Err(ABS_MSG.into());
    };
    let mut parts: Vec<&str> = Vec::new();
    for c in rest.split(sep) {
        match c {
            "" | "." => {}
            ".." => { parts.pop(); }
            c => parts.push(c),
        }
    }
    if parts.is_empty() { return Ok(root.to_string()); }
    Ok(format!("{}{}{}", root.trim_end_matches(sep), sep, parts.join(&sep.to_string())))
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::model::{Account, LimitWindow, Rule};

    const ROUTES: &str = "/tmp/a\t/x/acct-a\n/tmp/a/b\t-\ndefault\t/x/acct-d\n";

    fn acct(id: &str, dir: &str) -> Account {
        Account { id: id.into(), name: id.into(), flag: "a".into(), dir: dir.into(), email: None, plan: None, pending: false }
    }

    fn lim(five: f64) -> Limits {
        Limits {
            five_hour: Some(LimitWindow { percent: five, resets_at: None }),
            weekly: None,
            fetched_at: 0,
            stale: false,
            error: None,
            needs_sign_in: false,
            note: None,
        }
    }

    #[test]
    fn zsh_selftest_cases() {
        assert_eq!(resolve_in(ROUTES, "/tmp/a", false).as_deref(), Some("/x/acct-a"));
        assert_eq!(resolve_in(ROUTES, "/tmp/a/b/c", false), None);
        assert_eq!(resolve_in(ROUTES, "/tmp/ab", false).as_deref(), Some("/x/acct-d"));
        assert_eq!(resolve_in(ROUTES, "/tmp", false).as_deref(), Some("/x/acct-d"));
    }

    #[test]
    fn resolve_root_and_comments() {
        assert_eq!(resolve_in("# c\n\n/\t/x/root\n", "/anything/here", false).as_deref(), Some("/x/root"));
        assert_eq!(resolve_in("/tmp/a\t/x/a\n", "/tmp/a/", false).as_deref(), Some("/x/a"));
        assert_eq!(resolve_in("/tmp/a\t/x/a\n", "/tmp/b", false), None);
    }

    #[test]
    fn resolve_windows_mode() {
        let r = "C:\\Work\t/x/work\ndefault\t-\n";
        assert_eq!(resolve_in(r, "c:\\work\\x", true).as_deref(), Some("/x/work"));
        assert_eq!(resolve_in(r, "C:/Work/x", true).as_deref(), Some("/x/work"));
        assert_eq!(resolve_in(r, "C:\\Workshop", true), None);
        assert_eq!(resolve_in(r, "c:\\work\\x", false), None, "unix mode is case-sensitive");
        let root = "C:\\\t/x/c\n";
        assert_eq!(resolve_in(root, "c:\\foo", true).as_deref(), Some("/x/c"));
        assert_eq!(resolve_in(root, "D:\\foo", true), None);
        assert_eq!(resolve_in(r, r"\\?\C:\Work\x", true).as_deref(), Some("/x/work"), "verbatim prefix");
        assert_eq!(normalize_in(r"\\?\C:\Work\", true).as_deref(), Ok(r"C:\Work"));
        assert_eq!(normalize_in(r"\\?\UNC\srv\share\d", true).as_deref(), Ok(r"\\srv\share\d"));
        let unc = "\\\\srv\\share\t/x/s\n";
        assert_eq!(resolve_in(unc, "\\\\SRV\\share\\dir", true).as_deref(), Some("/x/s"));
    }

    #[test]
    fn routes_text_orders_and_marks_primary() {
        let paths = Paths::from_home("/h");
        let cfg = Config {
            accounts: vec![acct("primary", "/h/.claude"), acct("work", "/h/.claude-work"), acct("side", "/h/.claude-side")],
            rules: vec![
                Rule { path: "/h/p".into(), account_id: "primary".into(), allow_overflow: false },
                Rule { path: "/h/p/longer".into(), account_id: "side".into(), allow_overflow: true },
                Rule { path: "/h/bad\tpath".into(), account_id: "work".into(), allow_overflow: false },
                Rule { path: "/w".into(), account_id: "work".into(), allow_overflow: false },
            ],
            default_id: "work".into(),
            ..Config::default()
        };
        let mut limits = HashMap::new();
        limits.insert("side".to_string(), lim(95.0));
        let hot = "# generated by Claude Anchor — edit in the app\n/h/p/longer\t/h/.claude-work\n/h/p\t-\n/w\t/h/.claude-work\ndefault\t/h/.claude-work\n";
        assert_eq!(routes_text(&cfg, &limits, &paths), hot);
        limits.insert("side".to_string(), lim(50.0));
        assert!(routes_text(&cfg, &limits, &paths).contains("/h/p/longer\t/h/.claude-side\n"));
    }

    #[test]
    fn write_routes_private_file() {
        let home = tempfile::tempdir().unwrap();
        let paths = Paths::from_home(home.path());
        let cfg = Config { accounts: vec![acct("primary", "/h/.claude")], ..Config::default() };
        write_routes(&cfg, &HashMap::new(), &paths).unwrap();
        let text = std::fs::read_to_string(paths.routes()).unwrap();
        assert_eq!(text, routes_text(&cfg, &HashMap::new(), &paths));
        #[cfg(unix)]
        {
            use std::os::unix::fs::PermissionsExt;
            let mode = std::fs::metadata(paths.routes()).unwrap().permissions().mode();
            assert_eq!(mode & 0o777, 0o600);
        }
    }

    #[test]
    fn project_slug_rules() {
        assert_eq!(project_slug("/Users/me/proj"), "-Users-me-proj");
        assert_eq!(project_slug("C:\\Users\\me\\proj"), "C--Users-me-proj");
        assert_eq!(project_slug("/tmp/café"), "-tmp-caf-");
        assert_eq!(project_slug("/x😀"), "-x--", "astral chars are two UTF-16 units");
        // Expected value taken from Claude Code's JS formula: 200-char prefix plus base36 of the hash.
        let long = format!("/{}", "a".repeat(300));
        assert_eq!(project_slug(&long), format!("-{}-vtkmfl", "a".repeat(199)));
    }

    #[test]
    fn base36_digits() {
        assert_eq!(base36(0), "0");
        assert_eq!(base36(35), "z");
        assert_eq!(base36(36), "10");
        assert_eq!(base36(i64::from(i32::MIN).unsigned_abs()), "zik0zk");
    }

    #[test]
    fn normalize_unix() {
        assert_eq!(normalize_in("/a/b/", false).as_deref(), Ok("/a/b"));
        assert_eq!(normalize_in("/a/./b/../c", false).as_deref(), Ok("/a/c"));
        assert_eq!(normalize_in("//x//y", false).as_deref(), Ok("/x/y"));
        assert_eq!(normalize_in("/", false).as_deref(), Ok("/"));
        assert_eq!(normalize_in("/../..", false).as_deref(), Ok("/"));
        assert_eq!(normalize_in("rel/x", false), Err(ABS_MSG.to_string()));
        assert_eq!(normalize_in("/a\tb", false), Err(TAB_MSG.to_string()));
        assert_eq!(normalize_in("/a\nb", false), Err(TAB_MSG.to_string()));
    }

    #[test]
    fn normalize_windows() {
        assert_eq!(normalize_in("c:/Work/", true).as_deref(), Ok("c:\\Work"));
        assert_eq!(normalize_in("C:\\", true).as_deref(), Ok("C:\\"));
        assert_eq!(normalize_in("C:\\a\\..\\b", true).as_deref(), Ok("C:\\b"));
        assert_eq!(normalize_in("\\\\srv\\share\\x\\", true).as_deref(), Ok("\\\\srv\\share\\x"));
        assert_eq!(normalize_in("\\\\srv\\", true), Err(ABS_MSG.to_string()));
        assert_eq!(normalize_in("/Work", true), Err(ABS_MSG.to_string()));
        assert_eq!(normalize_in("Work\\x", true), Err(ABS_MSG.to_string()));
    }
}
